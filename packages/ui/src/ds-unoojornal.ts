'use client';

/**
 * Ponte para a seção **Unoojornal** do `@unooria/design-system` (0.2.24).
 *
 * Existe pelo mesmo motivo de `ds.ts` e das outras pontes: o pacote usa hooks
 * mas não publica a diretiva 'use client' no bundle, e reexportar por aqui marca
 * a seção inteira de uma vez.
 *
 * O Unoojornal é o jornal digital com a identidade da Unooria (paleta roxa,
 * Open Sans, Material Symbols), com a estrutura editorial do "Jornal da Escola":
 * cabeçalho com faixa de edição (`Logo`, `Masthead`, `EditionBar`), capa, lista
 * de matérias com filtros (`FilterPill`, `FilterBar`), cartões de reportagem
 * (`ArticleCard`, `GalleryImage`, `GalleryGrid`), matéria aberta (`Figure`,
 * `ArticleBody`), `Modal`, `Toast` e `EmptyState`. Tokens `--ujn-*`, classes
 * `ujn-`, tema por `data-ujn-theme` (`light` | `dark`).
 *
 * ⚠️ **A folha de fonte é obrigatória** (`/fonts/unoojornal.css`, além de
 * `/unoojornal.css`): o `Icon` é ligadura do Material Symbols, e sem a folha o
 * NOME do glifo aparece como texto.
 *
 * A importação é pelo SUBCAMINHO (`@unooria/design-system/unoojornal`): o
 * subcaminho preserva o tree-shaking.
 *
 * ONDE USAR: o jornal da exp03ef1b (Nina e a Notícia que Desapareceu), em DS
 * HÍBRIDO autorizado pela ADR-197: o jornal (cabeçalho, reportagens, foto
 * ampliada, filtro, selos, aviso sem sinal, erro de mídia) é `unoojornal`; a
 * MECÂNICA da missão (balão da Nina, caixa de escolha, carimbos, etiquetas da
 * ficha, esteira de blocos, pausa) é `unooria`, pela `@edu/ui/ds`. Fora dessa
 * exceção registrada, as seções não se misturam.
 *
 * Os nomes que COLIDEM com a plataforma (`ds.ts`) ganham o sufixo `Ujn`, o
 * prefixo dos tipos da própria seção (`UjnIconName`), pela mesma regra do
 * `Unv` em `ds-unoovista.ts`: nunca um alias criativo, porque quem procura no
 * Storybook precisa achar pelo nome do catálogo.
 */
